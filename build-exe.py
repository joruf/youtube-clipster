#!/usr/bin/env python3
"""Build YouTube Clipster as a single executable file.

One command, the same on every platform - run it on the system the file is
meant for, because PyInstaller cannot build for another one:

    ./build-exe.py              Linux   -> dist/youtube-clipster-linux-x86_64-<version>-build<build>
    py build-exe.py             Windows -> dist/youtube-clipster-windows-x86_64-<version>-build<build>.exe

What it does:

1. creates a private build environment in ``build/exe/venv`` (Linux: with the
   system's PyGObject linked in, which pip cannot install - without it the tray
   icon has no menu),
2. installs PyInstaller and every package the program carries,
3. stages the sources, which the executable needs as data: the Android setup
   sends them to the phone, and the icons and the phone interface live there,
4. runs PyInstaller and checks that the result starts.

yt-dlp is left out on purpose: the executable downloads yt-dlp's own release on
the first start and keeps it current, so YouTube changes never wait for a new
build.  Its helper packages (certificates, brotli, websockets, ...) change
rarely and are built in, and so is the whole standard library, because the
yt-dlp that arrives later may import any part of it.

Options:

    --clean     rebuild the build environment from scratch
    --keep-env  reuse the build environment without updating its packages

Author:  Joachim Ruf, Loresoft.de
License: GPLv3 - the author's name must be credited upon publication and modification.
"""

from __future__ import annotations

import argparse
import importlib.metadata
import importlib.util
import os
import pkgutil
import shutil
import subprocess
import sys
import venv
from pathlib import Path
from typing import Iterator, List

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

from clipster import APP_VERSION_FULL, android, dependencies, paths, updater  # noqa: E402

BUILD_DIR = ROOT / "build" / "exe"
VENV_DIR = BUILD_DIR / "venv"
STAGE_DIR = BUILD_DIR / "stage"
WORK_DIR = BUILD_DIR / "work"
SPEC_FILE = WORK_DIR / "youtube-clipster.spec"
DIST_DIR = ROOT / "dist"

#: Needs 6.9 or newer for ``PYINSTALLER_RESET_ENVIRONMENT``, which the updater
#: sets so a restarted executable unpacks itself afresh.
PYINSTALLER_SPEC = "pyinstaller>=6.9"

#: The packages yt-dlp's ``default`` extra pulls in, as (pip name, import name).
#: yt-dlp itself comes as a download; these must already be in the executable.
YTDLP_HELPERS = (
    ("brotli", "brotli"),
    ("certifi", "certifi"),
    ("mutagen", "mutagen"),
    ("pycryptodomex", "Cryptodome"),
    ("requests", "requests"),
    ("urllib3", "urllib3"),
    ("websockets", "websockets"),
)

#: Modules that must never end up in the executable.
EXCLUDED_MODULES = ["yt_dlp", "yt_dlp_ejs"]

#: Parts of the standard library nothing at run time needs: tests, the IDE,
#: demos and the tools that build or install Python itself.
STDLIB_SKIP = ("test", "tests", "idlelib", "idle_test", "turtledemo", "turtle", "lib2to3",
               "ensurepip", "pydoc_data", "distutils", "venv", "antigravity", "this",
               "__phello__", "__hello__")

#: GTK's share data, limited to what a tray menu needs.  Unlimited, PyInstaller
#: packs every icon and theme of the build machine - over a gigabyte on Mint.
GTK_HOOK_CONFIG = {
    "gi": {
        "icons": [],
        "themes": [],
        "languages": ["de", "en"],
        "module-versions": {"Gtk": "3.0"},
    },
}

SPEC_TEMPLATE = '''# Generated by build-exe.py - edit that script, not this file.
from PyInstaller.utils.hooks import collect_all, collect_submodules

datas = {datas!r}
binaries = []
hiddenimports = {hidden!r}
for package in {submodules!r}:
    hiddenimports += collect_submodules(package)
for package in {collect!r}:
    package_datas, package_binaries, package_imports = collect_all(package)
    datas += package_datas
    binaries += package_binaries
    hiddenimports += package_imports

a = Analysis(
    [{entry!r}],
    pathex=[{root!r}],
    binaries=binaries,
    datas=datas,
    hiddenimports=hiddenimports,
    hookspath=[],
    hooksconfig={hooksconfig!r},
    runtime_hooks=[],
    excludes={excludes!r},
    noarchive=False,
)
pyz = PYZ(a.pure)
exe = EXE(
    pyz,
    a.scripts,
    a.binaries,
    a.datas,
    [],
    name={name!r},
    debug=False,
    strip=False,
    upx=False,
    runtime_tmpdir=None,
    # No console window on Windows; the setup shows its own window.
    console=False,
    icon={icon!r},
)
'''


def info(message: str) -> None:
    """Print a progress line."""
    print("[build-exe] " + message, flush=True)


def fail(message: str) -> None:
    """Print an error and stop with exit code 1."""
    print("[build-exe] ERROR: " + message, file=sys.stderr, flush=True)
    sys.exit(1)


def venv_python() -> Path:
    """Return the interpreter of the build environment."""
    if paths.IS_WINDOWS:
        return VENV_DIR / "Scripts" / "python.exe"
    return VENV_DIR / "bin" / "python"


def run(command: List[object], **kwargs) -> None:
    """Run a command and stop the build when it fails."""
    info("$ " + " ".join(str(part) for part in command))
    completed = subprocess.run([str(part) for part in command], **kwargs)
    if completed.returncode != 0:
        fail("command failed with exit code {0}".format(completed.returncode))


def check_build_host() -> None:
    """Stop early when this interpreter cannot produce a complete program."""
    if not hasattr(sys, "stdlib_module_names"):
        fail("building needs Python 3.10 or newer (the program itself still runs on {0}.{1}).".format(
            *dependencies.MINIMUM_PYTHON))
    try:
        import tkinter  # noqa: F401
    except ImportError:
        fail("tkinter is missing - Linux: sudo apt install python3-tk")
    if paths.IS_LINUX and system_gi() is None:
        info("WARNING: PyGObject is missing - the tray icon of this build will have no menu.")
        info("         Debian/Ubuntu/Mint: sudo apt install python3-gi gir1.2-ayatanaappindicator3-0.1")


def system_gi() -> "Path | None":
    """Return the PyGObject package of this interpreter, or ``None``."""
    spec = importlib.util.find_spec("gi")
    if spec is None or not spec.submodule_search_locations:
        return None
    return Path(list(spec.submodule_search_locations)[0])


def venv_site_packages() -> Path:
    """Return the ``site-packages`` directory of the build environment."""
    completed = subprocess.run([str(venv_python()), "-c", "import sysconfig; print(sysconfig.get_paths()['purelib'])"],
                               stdout=subprocess.PIPE, check=True)
    return Path(completed.stdout.decode().strip())


def bundled_packages() -> List[str]:
    """Return the pip packages to install into the build environment.

    Taken from the dependency table, minus yt-dlp, plus yt-dlp's helpers.
    """
    platform = dependencies.current_platform()
    packages = [PYINSTALLER_SPEC]
    for item in dependencies.pip_dependencies(platform):
        if item.module != "yt_dlp":
            packages.append(item.package)
    packages.extend(name for name, _module in YTDLP_HELPERS)
    return packages


def prepare_venv(clean: bool, keep: bool) -> None:
    """Create or refresh the build environment.

    It is created without the system packages, so nothing the build machine
    happens to have installed (numpy, lxml, ...) ends up in the executable.
    """
    if clean and VENV_DIR.exists():
        info("Removing the old build environment ...")
        shutil.rmtree(str(VENV_DIR))
    if not venv_python().exists():
        info("Creating the build environment in {0} ...".format(VENV_DIR))
        venv.EnvBuilder(with_pip=True).create(str(VENV_DIR))
    elif keep:
        info("Reusing the build environment as it is.")
        return
    run([venv_python(), "-m", "pip", "install", "--upgrade", "--disable-pip-version-check", "pip"])
    run([venv_python(), "-m", "pip", "install", "--upgrade", "--disable-pip-version-check"]
        + bundled_packages())
    gi = system_gi() if paths.IS_LINUX else None
    if gi is not None:
        # The package and its metadata: PyInstaller's hook reads the version.
        sources = [gi]
        try:
            sources.append(Path(str(importlib.metadata.distribution("pygobject")._path)))
        except (importlib.metadata.PackageNotFoundError, AttributeError):
            info("WARNING: no PyGObject metadata found - PyInstaller may reject the build.")
        site = venv_site_packages()
        for source in sources:
            link = site / source.name
            if not link.exists():
                info("Linking the system {0} into the build environment ...".format(source.name))
                link.symlink_to(source, target_is_directory=True)


def stage_sources() -> Path:
    """Copy the sources the executable carries as data.

    Exactly the files the Android setup would send from a checkout, plus the
    commit marker, so the phone installed from the executable can still tell
    which version it runs.

    :return: The staged project root.
    """
    target = STAGE_DIR / paths.FROZEN_SOURCE_DIR
    if STAGE_DIR.exists():
        shutil.rmtree(str(STAGE_DIR))
    members = android.bundle_members(ROOT)
    for source in members:
        destination = target / source.relative_to(ROOT)
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(str(source), str(destination))
    commit = updater.installed_commit(ROOT)
    if commit:
        updater.write_marker(commit, target)
    else:
        info("WARNING: no git commit found - a phone set up from this build will offer a reinstall.")
    info("Staged {0} source files.".format(len(members)))
    return target


def _skipped(name: str) -> bool:
    """Return ``True`` for a standard library module the build leaves out."""
    parts = name.split(".")
    return name.startswith(("_test", "xx")) or any(part in STDLIB_SKIP for part in parts)


def _submodules(folder: Path, prefix: str) -> Iterator[str]:
    """Yield every module below a package directory, without importing it."""
    for found in pkgutil.iter_modules([str(folder)]):
        name = "{0}.{1}".format(prefix, found.name)
        if _skipped(name):
            continue
        yield name
        if found.ispkg:
            yield from _submodules(folder / found.name, name)


def stdlib_modules() -> List[str]:
    """Return every standard library module available on this platform.

    PyInstaller only packs what it sees imported.  yt-dlp is not there to be
    seen - it arrives as a download - so without this list it would fail on the
    first module only it uses (``sqlite3`` for browser cookies, for example).

    :return: Dotted module names.
    """
    found: List[str] = []
    for name in sorted(getattr(sys, "stdlib_module_names", ())):
        if _skipped(name):
            continue
        try:
            spec = importlib.util.find_spec(name)
        except (ImportError, ValueError):
            continue
        if spec is None:
            # Belongs to another platform, e.g. winreg on Linux.
            continue
        found.append(name)
        for location in spec.submodule_search_locations or []:
            found.extend(_submodules(Path(location), name))
    return found


def spec_text(staged: Path) -> str:
    """Return the PyInstaller spec file for this platform.

    :param staged: The staged project root from :func:`stage_sources`.
    :return: The content of the spec file.
    """
    name = paths.executable_name()
    if name.endswith(".exe"):
        name = name[:-4]
    submodules = ["clipster", "pystray", "qrcode"]
    if paths.IS_LINUX:
        submodules.append("Xlib")
    icon = ROOT / "assets" / "icons" / "youtube-clipster.ico"
    return SPEC_TEMPLATE.format(
        datas=[(str(staged), paths.FROZEN_SOURCE_DIR)],
        hidden=stdlib_modules() + ["PIL._tkinter_finder", "PIL.ImageTk"],
        submodules=submodules,
        collect=[module for _package, module in YTDLP_HELPERS],
        entry=str(ROOT / "run.py"),
        root=str(ROOT),
        hooksconfig=GTK_HOOK_CONFIG,
        excludes=EXCLUDED_MODULES,
        name=name,
        icon=str(icon) if paths.IS_WINDOWS and icon.is_file() else None,
    )


def smoke_test(executable: Path) -> None:
    """Start the result once and make sure it answers."""
    info("Starting {0} --version ...".format(executable.name))
    completed = subprocess.run([str(executable), "--version"], stdout=subprocess.PIPE,
                               stderr=subprocess.STDOUT, timeout=300)
    output = completed.stdout.decode("utf-8", errors="replace").strip()
    if completed.returncode != 0:
        fail("the executable did not start (exit code {0}):\n{1}".format(completed.returncode, output))
    # A windowed Windows build has no stdout to print to; the exit code has to do.
    if output and APP_VERSION_FULL not in output:
        fail("the executable reports {0!r}, expected {1}".format(output, APP_VERSION_FULL))
    info("OK: " + (output or "exit code 0"))


def main() -> int:
    """Run the whole build."""
    parser = argparse.ArgumentParser(description="Build YouTube Clipster as a single executable file.")
    parser.add_argument("--clean", action="store_true", help="rebuild the build environment from scratch")
    parser.add_argument("--keep-env", action="store_true",
                        help="reuse the build environment without updating its packages")
    args = parser.parse_args()

    info("YouTube Clipster {0} for {1}".format(APP_VERSION_FULL, paths.executable_name()))
    check_build_host()
    prepare_venv(clean=args.clean, keep=args.keep_env)
    staged = stage_sources()
    WORK_DIR.mkdir(parents=True, exist_ok=True)
    SPEC_FILE.write_text(spec_text(staged), encoding="utf-8")
    run([venv_python(), "-m", "PyInstaller", "--noconfirm", "--clean",
         "--distpath", DIST_DIR, "--workpath", WORK_DIR, SPEC_FILE], cwd=str(ROOT))

    result = DIST_DIR / paths.executable_name()
    if not result.is_file():
        fail("PyInstaller finished but {0} is missing".format(result))
    smoke_test(result)
    info("Done: {0} ({1:.1f} MB)".format(result, result.stat().st_size / 1048576))
    info("This file runs on {0} only; build on the other system for its own file.".format(
        "Windows" if paths.IS_WINDOWS else ("macOS" if paths.IS_MACOS else "Linux")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
